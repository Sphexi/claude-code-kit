#!/usr/bin/env python3
"""Inline the canonical shared blocks into every marked payload file.

The files under ``shared/`` are the single source of truth for prose that has
to appear identically in many payload files. This script copies each one into
every target carrying its marker pair::

    <!-- TERSENESS:START -->
    ...generated, do not edit...
    <!-- TERSENESS:END -->

Two blocks exist. ``TERSENESS`` governs how a response is written and comes in
two variants, because a subagent runs its own system prompt and never sees the
main conversation's output style; the variant is chosen by path, with anything
inside an ``agents`` directory getting the subagent text. ``CODE-STANDARDS``
governs comments and test suites in code that is written, and has one variant
for every target.

Targets are discovered by marker presence rather than a hardcoded list, so
adding an agent, an output style, or a second block to an existing file
requires no change here. A file may carry either marker pair or both.

Files are fully regenerated, never patched in place, and the operation is
idempotent — running twice produces byte-identical output.

Exit codes:
    0   Success. In ``--check`` mode, every target is up to date.
    1   ``--check`` only: at least one target is stale.
    2   An error prevented the run (missing source, unbalanced markers).
"""

from __future__ import annotations

import argparse
import sys
from dataclasses import dataclass
from pathlib import Path

GENERATED_NOTICE = (
    "<!-- Generated by build/inline_shared.py — do not edit. "
    "Source: shared/{source} -->"
)

SHARED_DIR = "shared"

DEFAULT_ROOTS = ("claude",)

#: Directory names never descended into when discovering targets.
SKIP_DIRS = frozenset({".git", "__pycache__", "node_modules", ".pytest_cache"})


@dataclass(frozen=True)
class Block:
    """One shared block: its marker name and the sources it may draw on.

    Attributes:
        name: Marker name, e.g. ``"TERSENESS"``.
        variants: Mapping of variant key to filename under ``shared/``. A block
            with a single ``"all"`` entry is path-independent.
    """

    name: str
    variants: dict[str, str]

    @property
    def start(self) -> str:
        """Opening marker for this block."""
        return f"<!-- {self.name}:START -->"

    @property
    def end(self) -> str:
        """Closing marker for this block."""
        return f"<!-- {self.name}:END -->"

    def variant_for(self, path: Path) -> str:
        """Variant key this block supplies to `path`.

        Args:
            path: Target file the block is being inlined into.

        Returns:
            ``"subagent"`` for a file inside an ``agents`` directory when the
            block has that variant, otherwise the block's single key or
            ``"main"``.
        """
        if "all" in self.variants:
            return "all"
        if "agents" in path.parts[:-1]:
            return "subagent"
        return "main"


#: Every block this script maintains, in the order it reports them.
BLOCKS: tuple[Block, ...] = (
    Block(
        name="TERSENESS",
        variants={
            "main": "terseness-main.md",
            "subagent": "terseness-subagent.md",
        },
    ),
    Block(name="CODE-STANDARDS", variants={"all": "code-standards.md"}),
)

ALL_MARKERS = tuple(
    marker for block in BLOCKS for marker in (block.start, block.end)
)


class InlineError(Exception):
    """A target file or shared source could not be processed."""


def repo_root() -> Path:
    """Absolute path of the repository root, resolved from this file."""
    return Path(__file__).resolve().parents[1]


def load_sources(root: Path) -> dict[str, str]:
    """Read every shared source named by :data:`BLOCKS`.

    Args:
        root: Repository root containing the ``shared/`` directory.

    Returns:
        Mapping of filename to that file's prose, whitespace stripped.

    Raises:
        InlineError: If a source is missing, empty, or itself contains a
            marker, which would nest a generated region inside another.
    """
    sources: dict[str, str] = {}
    for block in BLOCKS:
        for filename in block.variants.values():
            if filename in sources:
                continue
            path = root / SHARED_DIR / filename
            if not path.is_file():
                raise InlineError(f"missing shared source: {path}")
            text = path.read_text(encoding="utf-8").strip()
            if not text:
                raise InlineError(f"shared source is empty: {path}")
            if any(marker in text for marker in ALL_MARKERS):
                raise InlineError(
                    f"shared source must not contain markers: {path}"
                )
            sources[filename] = text
    return sources


def discover_targets(roots: list[Path]) -> list[Path]:
    """Find every markdown file under `roots` carrying any start marker.

    Args:
        roots: Directories (or individual files) to search.

    Returns:
        Sorted list of target paths. Files that are unreadable as UTF-8 are
        skipped rather than raising — they cannot contain a marker.
    """
    starts = tuple(block.start for block in BLOCKS)
    found: set[Path] = set()
    for root in roots:
        if root.is_file():
            candidates = [root]
        else:
            candidates = sorted(root.rglob("*.md"))
        for candidate in candidates:
            if SKIP_DIRS.intersection(candidate.parts):
                continue
            try:
                text = candidate.read_text(encoding="utf-8")
            except (OSError, UnicodeDecodeError):
                continue
            if any(marker in text for marker in starts):
                found.add(candidate)
    return sorted(found)


def render(text: str, block: Block, body: str, source: str) -> str:
    """Return `text` with `block`'s region replaced by `body`.

    Args:
        text: Full current content of the target file.
        block: The block whose region is being regenerated.
        body: Prose to inline, without markers.
        source: Filename of the shared source, for the generated notice.

    Returns:
        The complete regenerated file content.

    Raises:
        InlineError: If the markers are unbalanced, out of order, or if more
            than one pair for this block is present.
    """
    starts = text.count(block.start)
    ends = text.count(block.end)

    if starts == 0:
        raise InlineError(f"no {block.start} found")
    if ends == 0:
        raise InlineError(f"{block.start} present but {block.end} missing")
    if starts > 1 or ends > 1:
        raise InlineError(
            f"expected exactly one {block.name} block, found {starts} start "
            f"and {ends} end markers"
        )

    start_at = text.index(block.start)
    end_at = text.index(block.end)
    if end_at < start_at:
        raise InlineError(f"{block.end} appears before {block.start}")

    prefix = text[:start_at]
    suffix = text[end_at + len(block.end):]

    region = "\n".join(
        [
            block.start,
            GENERATED_NOTICE.format(source=source),
            "",
            body,
            "",
            block.end,
        ]
    )
    return prefix + region + suffix


def process(
    target: Path, sources: dict[str, str], root: Path
) -> tuple[str, str]:
    """Compute the current and regenerated content of one target.

    Every block whose start marker is present is regenerated; blocks absent
    from the file are left alone.

    Args:
        target: Path to the target file.
        sources: Mapping from :func:`load_sources`.
        root: Repository root, used only for error message paths.

    Returns:
        A ``(current, rendered)`` pair.

    Raises:
        InlineError: If a block's markers are malformed. The message is
            prefixed with the target's path relative to the repo root.
    """
    current = target.read_text(encoding="utf-8")
    rendered = current
    for block in BLOCKS:
        if block.start not in rendered:
            continue
        filename = block.variants[block.variant_for(target)]
        try:
            rendered = render(rendered, block, sources[filename], filename)
        except InlineError as exc:
            raise InlineError(f"{_relative(target, root)}: {exc}") from exc
    return current, rendered


def build_parser() -> argparse.ArgumentParser:
    """Construct the command-line argument parser."""
    names = ", ".join(block.name for block in BLOCKS)
    parser = argparse.ArgumentParser(
        prog="inline_shared.py",
        description=(
            f"Inline shared/*.md into every file carrying a marker pair "
            f"({names})."
        ),
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="report stale targets and exit non-zero; write nothing",
    )
    parser.add_argument(
        "--root",
        action="append",
        dest="roots",
        metavar="PATH",
        help=(
            "directory or file to search for targets; repeatable. "
            f"Default: {', '.join(DEFAULT_ROOTS)}"
        ),
    )
    parser.add_argument(
        "--repo-root",
        type=Path,
        default=None,
        metavar="PATH",
        help="repository root; defaults to the parent of build/",
    )
    return parser


def main(argv: list[str] | None = None) -> int:
    """Entry point.

    Args:
        argv: Argument list, defaulting to ``sys.argv[1:]``.

    Returns:
        Process exit code — 0 success, 1 stale under ``--check``, 2 error.
    """
    args = build_parser().parse_args(argv)
    root = (args.repo_root or repo_root()).resolve()

    raw_roots = args.roots if args.roots else list(DEFAULT_ROOTS)
    roots: list[Path] = []
    for entry in raw_roots:
        path = Path(entry)
        if not path.is_absolute():
            path = root / path
        if not path.exists():
            print(f"error: root does not exist: {path}", file=sys.stderr)
            return 2
        roots.append(path)

    try:
        sources = load_sources(root)
    except InlineError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2

    targets = discover_targets(roots)
    if not targets:
        print("no targets found (no file carries a shared-block marker)")
        return 0

    stale: list[Path] = []
    written: list[Path] = []
    for target in targets:
        try:
            current, rendered = process(target, sources, root)
        except InlineError as exc:
            print(f"error: {exc}", file=sys.stderr)
            return 2
        if current == rendered:
            continue
        stale.append(target)
        if not args.check:
            target.write_text(rendered, encoding="utf-8", newline="\n")
            written.append(target)

    if args.check:
        if stale:
            print(f"{len(stale)} target(s) stale:", file=sys.stderr)
            for target in stale:
                print(f"  {_relative(target, root)}", file=sys.stderr)
            return 1
        print(f"{len(targets)} target(s) up to date")
        return 0

    if written:
        print(f"updated {len(written)} of {len(targets)} target(s):")
        for target in written:
            print(f"  {_relative(target, root)}")
    else:
        print(f"{len(targets)} target(s) already up to date")
    return 0


def _relative(path: Path, root: Path) -> Path:
    """Path relative to `root`, or the absolute path if it lies outside."""
    try:
        return path.relative_to(root)
    except ValueError:
        return path


if __name__ == "__main__":
    sys.exit(main())
